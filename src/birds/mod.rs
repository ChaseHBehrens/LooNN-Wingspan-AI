use paste::paste;

macro_rules! card_modules {
    ($($name:ident),* $(,)?) => {
        $(
            pub mod $name;
            pub use $name::*;
        )*
        paste! {
            /// Represents the full deck of bird cards
            pub static BIRDS: [Bird; <[()]>::len(&[$(card_modules!(@replace $name ())),*])] = [
                $($name::[< $name:upper >]),*
            ];
        }
    };
    (@replace $name:ident $sub:expr) => { $sub };
}

